#!/usr/bin/env node
/* Generates sw.js: a service worker that precaches every file the game needs, so the hosted game
 * works offline after the first visit and can be installed to a home screen. The cache name
 * includes a hash of all files, so any change ships as an update. Run after changing files. */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..');

function files() {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const refs = [...html.matchAll(/(?:src|href)="([^"#?]+)"/g)].map((m) => m[1]).filter((r) => !/^https?:/.test(r));
  const extra = ['index.html', 'manifest.webmanifest', 'css/style.css'];
  for (const dir of ['assets/fonts', 'assets/icons']) {
    for (const f of fs.readdirSync(path.join(ROOT, dir))) if (/\.(woff2|png)$/.test(f)) extra.push(dir + '/' + f);
  }
  extra.push('assets/icon.svg');
  return [...new Set(refs.concat(extra))].sort();
}

function build() {
  const list = files();
  const h = crypto.createHash('sha256');
  for (const f of list) h.update(f).update(fs.readFileSync(path.join(ROOT, f)));
  const version = require(path.join(ROOT, 'package.json')).version;
  const cache = 'obeylol-' + version + '-' + h.digest('hex').slice(0, 10);
  return `/* OBEY? LOL. service worker — generated by tools/gen-sw.js, do not edit by hand. */
'use strict';
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(list, null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('obeylol-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(caches.match('index.html').then((hit) => hit || fetch(req)).catch(() => caches.match('index.html')));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;
}

if (require.main === module) {
  fs.writeFileSync(path.join(ROOT, 'sw.js'), build());
  console.log('Wrote sw.js with ' + files().length + ' files.');
}
module.exports = { files, build };
